// Generated by /ship coverage audit
// Value: protects=an oversized event is cut and later events kept, and the journal's count bound ends it with one marker;
//   fails_when=an oversized event is dropped or ends the journal, or the marker repeats or is missing;
//   why_new=nodeServerEvents tests do not push past the byte or count bounds; seam=none; no_claim=byte total bound (count bound stands in)
test('an oversized event is cut, later events are kept, and the event count ends the journal with one marker', () => {
  // Arrange
  const events: JournaledEvent[] = []
  const record = createNodeServerJournal(events, { sanitize: (text) => text })
  // Act
  record('node-server.output', {
    sequence: 1,
    elapsedMs: 0,
    channel: 'stdout',
    text: '\u0001'.repeat(4096),
  })
  record('node-server.output', {
    sequence: 2,
    elapsedMs: 1,
    channel: 'stdout',
    text: 'next',
  })
  const afterTwo = events.map((event) => event.sequence)
  const firstText = (events[0]?.detail as { text: string }).text
  for (let index = 0; index < MAX_EVENTS + 5; index += 1) {
    record('node-server.output', {
      sequence: index,
      elapsedMs: 0,
      channel: 'stdout',
      text: 'x',
    })
  }
  // Assert
  assert.deepEqual(afterTwo, [1, 2])
  assert.ok(Buffer.byteLength(JSON.stringify(events[0]?.detail)) <= 8192)
  assert.ok(firstText.length < 4096 && firstText.startsWith('\u0001'))
  assert.equal(events.length, MAX_EVENTS)
  assert.equal(
    events.filter((event) => event.type === 'node-server.events-truncated')
      .length,
    1,
  )
  assert.equal(events.at(-1)?.type, 'node-server.events-truncated')
})
