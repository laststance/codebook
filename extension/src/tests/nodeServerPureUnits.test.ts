/** A hand-moved clock: `advance` fires the armed timer once its delay passed. */
function createClock() {
  let nowMs = 0
  let timer: { at: number; callback: () => void } | undefined
  const clock: RunClock = {
    now: () => nowMs,
    set: (callback, delayMs) => {
      const armed = { at: nowMs + delayMs, callback }
      timer = armed
      return (): void => {
        if (timer === armed) timer = undefined
      }
    },
  }
  return {
    clock,
    advance(ms: number): void {
      nowMs += ms
      const due = timer
      if (due && due.at <= nowMs) {
        timer = undefined
        due.callback()
      }
    },
  }
}

// Generated by /ship coverage audit
// Value: protects=held pause time never counts toward the running limit, expiry fires after the remaining running time only;
//   fails_when=hold stops banking time or the timer is not cancelled while held, or resume re-arms the full limit;
//   why_new=no existing test drives RunningTimeLimit with a manual clock; seam=none; no_claim=real timers (hand-moved clock stands in)
test('a held pause does not count toward the time limit and expiry fires after the remaining running time', () => {
  // Arrange
  const { clock, advance } = createClock()
  let expired = 0
  const limit = new RunningTimeLimit(1000, clock, () => (expired += 1))
  limit.start()
  // Act
  advance(400)
  limit.hold()
  advance(5000)
  const expiredWhileHeld = expired
  const timeLeftWhileHeld = limit.hasTimeLeft()
  limit.release()
  advance(500)
  const expiredBeforeRemaining = expired
  advance(100)
  // Assert
  assert.equal(expiredWhileHeld, 0)
  assert.equal(timeLeftWhileHeld, true)
  assert.equal(expiredBeforeRemaining, 0)
  assert.equal(expired, 1)
  assert.equal(limit.hasTimeLeft(), false)
})

// Generated by /ship coverage audit
// Value: protects=nested holds need every release before counting resumes, and stop silences the limit for good;
//   fails_when=release resumes at the first release or stop leaves the timer armed;
//   why_new=no existing test covers hold nesting or stop; seam=none; no_claim=real timers (hand-moved clock stands in)
test('nested pauses resume the count only after every release and a stopped limit never expires', () => {
  // Arrange
  const { clock, advance } = createClock()
  let expired = 0
  const limit = new RunningTimeLimit(1000, clock, () => (expired += 1))
  limit.start()
  limit.hold()
  limit.hold()
  // Act
  limit.release()
  advance(2000)
  const expiredAfterOneRelease = expired
  limit.release()
  advance(900)
  const expiredBeforeLimit = expired
  limit.stop()
  advance(10_000)
  // Assert
  assert.equal(expiredAfterOneRelease, 0)
  assert.equal(expiredBeforeLimit, 0)
  assert.equal(expired, 0)
})

